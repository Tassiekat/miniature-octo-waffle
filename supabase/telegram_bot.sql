create table if not exists public.telegram_users (
  id bigint generated by default as identity primary key,
  telegram_id bigint not null unique,
  username text,
  first_name text,
  referral_code text not null unique,
  referred_by bigint references public.telegram_users(id),
  created_at timestamptz not null default now()
);

create table if not exists public.checkout_sessions (
  stripe_session_id text primary key,
  telegram_user_id bigint not null references public.telegram_users(telegram_id) on delete cascade,
  product_key text not null,
  referral_code text,
  status text not null default 'created',
  created_at timestamptz not null default now()
);

create table if not exists public.telecast_entitlements (
  telegram_user_id bigint not null references public.telegram_users(telegram_id) on delete cascade,
  product_key text not null,
  stripe_customer_id text,
  stripe_subscription_id text,
  stripe_session_id text,
  active boolean not null default false,
  expires_at timestamptz,
  updated_at timestamptz not null default now(),
  primary key (telegram_user_id, product_key)
);

create table if not exists public.referrals (
  id bigint generated by default as identity primary key,
  referral_code text not null,
  buyer_telegram_id bigint not null references public.telegram_users(telegram_id) on delete cascade,
  product_key text not null,
  stripe_session_id text not null unique,
  created_at timestamptz not null default now()
);

create index if not exists telegram_users_referral_code_idx on public.telegram_users(referral_code);
create index if not exists telecast_entitlements_customer_idx on public.telecast_entitlements(stripe_customer_id);
create index if not exists telecast_entitlements_subscription_idx on public.telecast_entitlements(stripe_subscription_id);

-- This backend uses the Supabase service-role key. Do not expose that key to the browser.

-- Telegram data is server-only; storefront entitlements are left unchanged.
alter table public.telegram_users enable row level security;
revoke all on public.telegram_users from anon, authenticated;
grant all on public.telegram_users to service_role;
alter table public.checkout_sessions enable row level security;
revoke all on public.checkout_sessions from anon, authenticated;
grant all on public.checkout_sessions to service_role;
alter table public.telecast_entitlements enable row level security;
revoke all on public.telecast_entitlements from anon, authenticated;
grant all on public.telecast_entitlements to service_role;
alter table public.referrals enable row level security;
revoke all on public.referrals from anon, authenticated;
grant all on public.referrals to service_role;
grant usage, select on sequence public.telegram_users_id_seq, public.referrals_id_seq to service_role;
